export const LEGAL_LINKS = [
  ["terms", "Соглашение", FileText],
  ["payments", "Оплата и возврат", WalletCards],
  ["privacy", "Конфиденциальность", ShieldCheck],
  ["data", "Обработка данных", FileText],
] as const;

export function LegalLinks({ className, showIcons = false }: { className?: string; showIcons?: boolean }) {
  return (
    <nav aria-label="Юридические документы" className={clsx("flex flex-wrap items-center gap-x-4 gap-y-2", className)}>
      {LEGAL_LINKS.map(([slug, label, Icon]) => (
        <Link key={slug} to={`/legal/${slug}`} className="inline-flex items-center gap-1.5 transition hover:text-white">
          {showIcons && <Icon className="h-3.5 w-3.5 text-nova-300" />}
          {label}
        </Link>
      ))}
    </nav>
  );
}


def render_input(fields: dict[str, str]) -> str:
    labels = {"topic": "Тема", "text": "Текст", "tone": "Тон", "audience": "Аудитория",
              "platform": "Площадка", "period": "Период", "notes": "Дополнительно"}
    return "\n".join(f"{labels.get(k, k)}: {v}" for k, v in fields.items() if v)

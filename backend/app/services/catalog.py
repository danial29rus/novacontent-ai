"""Premium services: guided multi-field wizards sold at a fixed price per run.

Unlike chat (billed by usage), a service has a flat price, so the user knows the cost up front.
"""

from dataclasses import dataclass, field


@dataclass(frozen=True)
class Field:
    name: str
    label: str
    placeholder: str = ""
    textarea: bool = False
    required: bool = True
    options: tuple[str, ...] = ()


@dataclass(frozen=True)
class Service:
    slug: str
    title: str
    emoji: str
    category: str
    description: str
    price: int  # sparks (✦) per run
    prompt: str
    fields: tuple[Field, ...]
    result: str = "text"  # text | agent
    model: str = "gpt-5.6-terra"  # preferred model slug; falls back to the default model
    max_tokens: int = 4096
    badge: str | None = None
    perks: tuple[str, ...] = field(default_factory=tuple)


